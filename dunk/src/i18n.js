function t(lang, key) {
  const dict = D[normLang(lang)];
  let s = dict[key];
  if (s === undefined) s = D.hu[key];
  if (s === undefined) return key;
  for (let i = 2; i < arguments.length; i++) s = s.split('{' + (i - 2) + '}').join(String(arguments[i]));
  return s;
}

const hasKey = (k) => Object.prototype.hasOwnProperty.call(D.hu, k);

module.exports = { t, normLang, hasKey };
